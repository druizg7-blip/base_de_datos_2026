SET SERVEROUTPUT ON
SET SQLBLANKLINES ON
DECLARE
  v_num NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_num FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME='FACTURA' AND COLUMN_NAME='MODALIDAD_ENTREGA';
  IF v_num=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE FACTURA ADD (MODALIDAD_ENTREGA VARCHAR2(20))';
    DBMS_OUTPUT.PUT_LINE('Columna FACTURA.MODALIDAD_ENTREGA creada');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Columna MODALIDAD_ENTREGA ya existe');
  END IF;
  SELECT COUNT(*) INTO v_num FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME='CK_FACTURA_MODALIDAD_ENTREGA';
  IF v_num=0 THEN
    EXECUTE IMMEDIATE q'[ALTER TABLE FACTURA ADD CONSTRAINT CK_FACTURA_MODALIDAD_ENTREGA
      CHECK (MODALIDAD_ENTREGA IN ('CAJA', 'ENVIO'))]';
    DBMS_OUTPUT.PUT_LINE('Restriccion de modalidad de entrega creada');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Restriccion de modalidad de entrega ya existe');
  END IF;
END;
/

SELECT COLUMN_NAME,DATA_TYPE,DATA_LENGTH,NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME='FACTURA' AND COLUMN_NAME='MODALIDAD_ENTREGA';
SELECT CONSTRAINT_NAME,STATUS,VALIDATED
FROM USER_CONSTRAINTS WHERE TABLE_NAME='FACTURA' AND CONSTRAINT_NAME='CK_FACTURA_MODALIDAD_ENTREGA';
SELECT NVL(MODALIDAD_ENTREGA,'SIN CLASIFICAR') AS ENTREGA, COUNT(*) AS FACTURAS
FROM FACTURA GROUP BY NVL(MODALIDAD_ENTREGA,'SIN CLASIFICAR') ORDER BY ENTREGA;
SELECT OBJECT_NAME,OBJECT_TYPE,STATUS FROM USER_OBJECTS WHERE STATUS <> 'VALID'
  AND OBJECT_TYPE IN ('TRIGGER','PROCEDURE','FUNCTION','PACKAGE','PACKAGE BODY')
ORDER BY OBJECT_TYPE,OBJECT_NAME;