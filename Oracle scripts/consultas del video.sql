SELECT USER AS ESQUEMA, SYS_CONTEXT('USERENV', 'DB_NAME') AS BASE_DE_DATOS FROM DUAL;
SELECT OBJECT_TYPE, COUNT(*) AS TOTAL
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN ('TABLE','VIEW','SEQUENCE','TRIGGER','PROCEDURE','FUNCTION','PACKAGE','PACKAGE BODY')
GROUP BY OBJECT_TYPE ORDER BY OBJECT_TYPE;
SELECT TABLE_NAME FROM USER_TABLES ORDER BY TABLE_NAME;

SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('FACTURA','DETALLE_FACTURA','PAGO_CLIENTE','EMPLEADO','ENVIO')
  AND CONSTRAINT_TYPE IN ('P','R','C')
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;


SELECT
    t.TRIGGER_NAME,
    t.TABLE_NAME,
    t.TRIGGER_TYPE,
    t.TRIGGERING_EVENT,
    t.STATUS AS HABILITADO,
    o.STATUS AS COMPILACION
FROM USER_TRIGGERS t
JOIN USER_OBJECTS o
    ON o.OBJECT_NAME = t.TRIGGER_NAME
   AND o.OBJECT_TYPE = 'TRIGGER'
ORDER BY t.TABLE_NAME, t.TRIGGER_NAME;



