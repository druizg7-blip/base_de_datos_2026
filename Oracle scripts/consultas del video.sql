SELECT
    NOMBRE_USUARIO,
    LENGTH(CLAVE) AS LONGITUD_HASH,
    SUBSTR(CLAVE, 1, 12) || '...' AS MUESTRA_HASH,
    CASE
        WHEN REGEXP_LIKE(CLAVE, '^[0-9a-f]{64}$', 'i')
        THEN 'FORMATO SHA-256'
        ELSE 'REVISAR'
    END AS VERIFICACION
FROM USUARIO
ORDER BY NOMBRE_USUARIO;

    SELECT
    p.NOMBRE AS PRODUCTO,
    m.CANTIDAD AS CANTIDAD_VENDIDA,
    m.EXISTENCIA_ANTERIOR,
    m.EXISTENCIA_NUEVA,
    m.EXISTENCIA_ANTERIOR - m.EXISTENCIA_NUEVA AS DESCUENTO,
    CASE
        WHEN m.EXISTENCIA_ANTERIOR - m.EXISTENCIA_NUEVA = m.CANTIDAD
        THEN 'DESCUENTO CORRECTO'
        ELSE 'REVISAR'
    END AS RESULTADO,
    m.REFERENCIA
FROM MOVIMIENTO_INVENTARIO m
JOIN PRODUCTO_SUCURSAL ps
    ON ps.ID_PRODUCTO_SUCURSAL = m.ID_PRODUCTO_SUCURSAL
JOIN PRODUCTO p
    ON p.ID_PRODUCTO = ps.ID_PRODUCTO
WHERE m.REFERENCIA = (
    SELECT 'FACTURA ' || SERIE || '-' || NUMERO
    FROM FACTURA
    WHERE ID_FACTURA = &ID_FACTURA
)
ORDER BY m.ID_MOVIMIENTO_INVENTARIO;


SELECT
    u.NOMBRE_USUARIO,
    p.NOMBRES || ' ' || p.APELLIDOS AS EMPLEADO,
    r.NOMBRE AS ROL,
    e.FECHA_BAJA,
    u.ESTADO_REGISTRO AS ESTADO_USUARIO,
    u.BLOQUEADO,
    CASE
        WHEN e.ID_EMPLEADO IS NULL THEN 'SIN EMPLEADO ASOCIADO'
        WHEN e.FECHA_BAJA IS NOT NULL THEN 'DESPEDIDO'
        WHEN e.ESTADO_REGISTRO <> 'A' THEN 'EMPLEADO INACTIVO'
        WHEN u.ESTADO_REGISTRO <> 'A' THEN 'CUENTA INACTIVA'
        WHEN u.BLOQUEADO = 'S' THEN 'CUENTA BLOQUEADA'
        ELSE 'ACTIVO'
    END AS SITUACION
FROM USUARIO u
LEFT JOIN EMPLEADO e
    ON e.ID_EMPLEADO = u.ID_EMPLEADO
LEFT JOIN PERSONA p
    ON p.ID_PERSONA = e.ID_PERSONA
JOIN ROL r
    ON r.ID_ROL = u.ID_ROL
ORDER BY SITUACION, u.NOMBRE_USUARIO;