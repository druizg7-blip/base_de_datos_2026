--crear el campo unificado en BITACORA si hace falta
DECLARE
  v_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_n FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME = 'BITACORA' AND COLUMN_NAME = 'USUARIO_CREACION';
  IF v_n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE BITACORA ADD (USUARIO_CREACION VARCHAR2(50))';
    DBMS_OUTPUT.PUT_LINE('BITACORA.USUARIO_CREACION creada');
  ELSE
    DBMS_OUTPUT.PUT_LINE('BITACORA.USUARIO_CREACION ya existe');
  END IF;
END;
