--cobertura de cada tabla
SELECT t.TABLE_NAME AS TABLA,
  CASE
    WHEN tr.TRIGGER_NAME IS NULL THEN 'FALTA AUDITORIA'
    WHEN o.STATUS <> 'VALID' THEN 'TRIGGER INVALIDO'
    WHEN tr.STATUS <> 'ENABLED' THEN 'TRIGGER DESHABILITADO'
    ELSE 'OK'
  END AS AUDITORIA,
  tr.TRIGGER_NAME AS TRIGGER_AUDITORIA
FROM USER_TABLES t
LEFT JOIN USER_TRIGGERS tr
  ON tr.TRIGGER_NAME = 'TRG_AUD_' || t.TABLE_NAME
LEFT JOIN USER_OBJECTS o
  ON o.OBJECT_NAME = tr.TRIGGER_NAME AND o.OBJECT_TYPE = 'TRIGGER'
WHERE t.TABLE_NAME <> 'BITACORA'
ORDER BY t.TABLE_NAME;
--resumen de cobertura
SELECT COUNT(*) AS TABLAS_EVALUADAS,
       SUM(CASE WHEN tr.TRIGGER_NAME IS NOT NULL
                     AND o.STATUS = 'VALID' AND tr.STATUS = 'ENABLED'
                THEN 1 ELSE 0 END) AS TABLAS_CUBIERTAS,
       SUM(CASE WHEN tr.TRIGGER_NAME IS NULL OR NVL(o.STATUS, 'INVALID') <> 'VALID'
                     OR NVL(tr.STATUS, 'DISABLED') <> 'ENABLED'
                THEN 1 ELSE 0 END) AS TABLAS_PENDIENTES
FROM USER_TABLES t
LEFT JOIN USER_TRIGGERS tr ON tr.TRIGGER_NAME = 'TRG_AUD_' || t.TABLE_NAME
LEFT JOIN USER_OBJECTS o ON o.OBJECT_NAME = tr.TRIGGER_NAME AND o.OBJECT_TYPE = 'TRIGGER'
WHERE t.TABLE_NAME <> 'BITACORA';
