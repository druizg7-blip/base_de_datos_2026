--guardar usuario autenticado de la web o el de SQL Developer
--no sobrescribe registros anteriores
CREATE OR REPLACE TRIGGER TRG_BI_BITACORA
BEFORE INSERT ON BITACORA FOR EACH ROW
DECLARE
  v_actor VARCHAR2(50);
BEGIN
  IF :NEW.ID_BITACORA IS NULL THEN
    :NEW.ID_BITACORA := SEQ_BITACORA.NEXTVAL;
  END IF;
  :NEW.FECHA_HORA := SYSTIMESTAMP;
  v_actor := SUBSTR(COALESCE(
    NULLIF(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'), 'ANONIMO'),
    SYS_CONTEXT('USERENV','SESSION_USER')), 1, 50);
  :NEW.USUARIO_CREACION := v_actor;
END;
/
--todas las tablas

DECLARE
  v_sql VARCHAR2(4000);
  v_total NUMBER := 0;
BEGIN
  FOR t IN (
    SELECT c.TABLE_NAME
    FROM USER_TAB_COLUMNS c
    JOIN USER_TABLES ut ON ut.TABLE_NAME = c.TABLE_NAME
    WHERE c.COLUMN_NAME = 'USUARIO_CREACION'
      AND c.TABLE_NAME <> 'BITACORA'
    ORDER BY c.TABLE_NAME
  ) LOOP
    v_sql := 'CREATE OR REPLACE TRIGGER TRG_UC_' || SUBSTR(t.TABLE_NAME,1,23) ||
       ' BEFORE INSERT ON ' || t.TABLE_NAME ||
       ' FOR EACH ROW BEGIN ' ||
       ':NEW.USUARIO_CREACION := SUBSTR(COALESCE(' ||
       'NULLIF(SYS_CONTEXT(''USERENV'',''CLIENT_IDENTIFIER''),''ANONIMO''),' ||
       'SYS_CONTEXT(''USERENV'',''SESSION_USER'')),1,50); ' ||
       'END;';
    EXECUTE IMMEDIATE v_sql;
    v_total := v_total + 1;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('Triggers de USUARIO_CREACION configurados: ' || v_total);
END;
