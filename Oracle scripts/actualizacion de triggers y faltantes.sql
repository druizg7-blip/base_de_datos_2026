       NVL(b.USUARIO_CREACION, NVL(u.NOMBRE_USUARIO,'No identificado (historico)')) USUARIO_CREACION
FROM BITACORA b LEFT JOIN USUARIO u ON u.ID_USUARIO=b.ID_USUARIO
