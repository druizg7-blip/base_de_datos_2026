DECLARE
  v_generador NUMBER;
  v_creados NUMBER := 0;
  v_existentes NUMBER := 0;
  v_estado VARCHAR2(10);
BEGIN
  SELECT COUNT(*) INTO v_generador
  FROM USER_OBJECTS
  WHERE OBJECT_NAME = 'PRC_GEN_TRG_BITACORA'
    AND OBJECT_TYPE = 'PROCEDURE' AND STATUS = 'VALID';
  IF v_generador <> 1 THEN
    RAISE_APPLICATION_ERROR(-20101, 'Generador de auditoria inexistente o invalido. No se han creado triggers.');
  END IF;
  FOR t IN (
    SELECT c.TABLE_NAME, MIN(cc.COLUMN_NAME) AS PK
    FROM USER_CONSTRAINTS c
    JOIN USER_CONS_COLUMNS cc
      ON cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
     AND cc.TABLE_NAME = c.TABLE_NAME
    WHERE c.CONSTRAINT_TYPE = 'P'
      AND c.TABLE_NAME <> 'BITACORA'
    GROUP BY c.TABLE_NAME
    HAVING COUNT(*) = 1
    ORDER BY c.TABLE_NAME
  ) LOOP
    SELECT COUNT(*) INTO v_existentes
    FROM USER_TRIGGERS
    WHERE TRIGGER_NAME = 'TRG_AUD_' || t.TABLE_NAME;
    IF v_existentes = 0 THEN
      PRC_GEN_TRG_BITACORA(t.TABLE_NAME, t.PK);
      SELECT MAX(STATUS) INTO v_estado
      FROM USER_OBJECTS
      WHERE OBJECT_TYPE = 'TRIGGER'
        AND OBJECT_NAME = 'TRG_AUD_' || t.TABLE_NAME;
      IF NVL(v_estado, 'INVALID') <> 'VALID' THEN
        RAISE_APPLICATION_ERROR(-20102, 'Trigger invalido: TRG_AUD_' || t.TABLE_NAME);
      END IF;
      v_creados := v_creados + 1;
      DBMS_OUTPUT.PUT_LINE('CREADO ' || t.TABLE_NAME);
    END IF;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('FINALIZADO. Triggers nuevos: ' || v_creados);
END;
