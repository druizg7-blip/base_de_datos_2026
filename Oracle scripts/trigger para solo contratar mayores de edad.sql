SELECT e.ID_EMPLEADO,
       e.ID_PERSONA,
       e.FECHA_CONTRATACION,
       p.FECHA_NACIMIENTO,
       CASE
         WHEN p.FECHA_NACIMIENTO IS NULL THEN 'SIN FECHA NACIMIENTO'
         WHEN EXTRACT(YEAR FROM e.FECHA_CONTRATACION) - EXTRACT(YEAR FROM p.FECHA_NACIMIENTO)
              - CASE WHEN TO_CHAR(e.FECHA_CONTRATACION,'MMDD') < TO_CHAR(p.FECHA_NACIMIENTO,'MMDD')
                     THEN 1 ELSE 0 END < 18 THEN 'MENOR AL CONTRATAR'
         ELSE 'OK'
       END AS RESULTADO
FROM EMPLEADO e
JOIN PERSONA p ON p.ID_PERSONA = e.ID_PERSONA
WHERE p.FECHA_NACIMIENTO IS NULL
   OR EXTRACT(YEAR FROM e.FECHA_CONTRATACION) - EXTRACT(YEAR FROM p.FECHA_NACIMIENTO)
      - CASE WHEN TO_CHAR(e.FECHA_CONTRATACION,'MMDD') < TO_CHAR(p.FECHA_NACIMIENTO,'MMDD')
             THEN 1 ELSE 0 END < 18
ORDER BY e.ID_EMPLEADO;

CREATE OR REPLACE TRIGGER TRG_EDAD_18_EMPLEADO
BEFORE INSERT OR UPDATE OF ID_PERSONA, FECHA_CONTRATACION ON EMPLEADO
FOR EACH ROW
DECLARE
  v_nacimiento PERSONA.FECHA_NACIMIENTO%TYPE;
  v_edad NUMBER;
BEGIN
  SELECT FECHA_NACIMIENTO INTO v_nacimiento
    FROM PERSONA
   WHERE ID_PERSONA = :NEW.ID_PERSONA;

  IF v_nacimiento IS NULL THEN
    RAISE_APPLICATION_ERROR(-20511,
      'Contratacion rechazada: la persona debe tener fecha de nacimiento.');
  END IF;

  IF :NEW.FECHA_CONTRATACION IS NULL THEN
    RAISE_APPLICATION_ERROR(-20512,
      'Contratacion rechazada: falta la fecha de contratacion.');
  END IF;

  v_edad := EXTRACT(YEAR FROM :NEW.FECHA_CONTRATACION)
            - EXTRACT(YEAR FROM v_nacimiento)
            - CASE WHEN TO_CHAR(:NEW.FECHA_CONTRATACION, 'MMDD') < TO_CHAR(v_nacimiento, 'MMDD')
                   THEN 1 ELSE 0 END;
  IF v_edad < 18 THEN
    RAISE_APPLICATION_ERROR(-20513,
      'Contratacion rechazada: debe tener 18 anios cumplidos en la fecha de contratacion.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20514,
      'Contratacion rechazada: la persona indicada no existe.');
END;
/

CREATE OR REPLACE TRIGGER TRG_EDAD_18_PERSONA
BEFORE UPDATE OF FECHA_NACIMIENTO ON PERSONA
FOR EACH ROW
DECLARE
  v_invalidos NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_invalidos
    FROM EMPLEADO e
   WHERE e.ID_PERSONA = :NEW.ID_PERSONA
     AND (
       :NEW.FECHA_NACIMIENTO IS NULL
       OR EXTRACT(YEAR FROM e.FECHA_CONTRATACION)
          - EXTRACT(YEAR FROM :NEW.FECHA_NACIMIENTO)
          - CASE WHEN TO_CHAR(e.FECHA_CONTRATACION, 'MMDD') < TO_CHAR(:NEW.FECHA_NACIMIENTO, 'MMDD')
                 THEN 1 ELSE 0 END < 18
     );

  IF v_invalidos > 0 THEN
    RAISE_APPLICATION_ERROR(-20515,
      'Cambio rechazado: la nueva fecha de nacimiento incumple la edad minima en una contratacion.');
  END IF;
END;
/

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_NAME IN ('TRG_EDAD_18_EMPLEADO', 'TRG_EDAD_18_PERSONA')
ORDER BY OBJECT_NAME;

SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM USER_ERRORS
WHERE NAME IN ('TRG_EDAD_18_EMPLEADO', 'TRG_EDAD_18_PERSONA')
ORDER BY NAME, SEQUENCE;
