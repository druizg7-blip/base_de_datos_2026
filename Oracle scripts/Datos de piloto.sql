--pilotos y entregas
--Ejecutar UNA VEZ desde SQL Developer como usuario propietario de las tablas.
--No elimina datos. Añade un ID_PILOTO opcional para conservar envíos anteriores.
DECLARE
  v_num NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_num FROM USER_TAB_COLUMNS WHERE TABLE_NAME='ENVIO' AND COLUMN_NAME='ID_PILOTO';
  IF v_num=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ENVIO ADD (ID_PILOTO NUMBER)';
    DBMS_OUTPUT.PUT_LINE('COLUMNA ENVIO.ID_PILOTO CREADA');
  ELSE DBMS_OUTPUT.PUT_LINE('COLUMNA ID_PILOTO YA EXISTE'); END IF;
  SELECT COUNT(*) INTO v_num FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='FK_ENVIO_PILOTO';
  IF v_num=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ENVIO ADD CONSTRAINT FK_ENVIO_PILOTO FOREIGN KEY (ID_PILOTO) REFERENCES EMPLEADO (ID_EMPLEADO)';
    DBMS_OUTPUT.PUT_LINE('FK ENVIO_PILOTO CREADA');
  END IF;
  SELECT COUNT(*) INTO v_num FROM USER_INDEXES WHERE INDEX_NAME='IX_ENVIO_ID_PILOTO';
  IF v_num=0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_ENVIO_ID_PILOTO ON ENVIO (ID_PILOTO)';
  END IF;
END;
/
--rol y permiso de mis entregas
DECLARE
  v_rol NUMBER;
  v_opcion NUMBER;
  v_menu NUMBER;
  v_num NUMBER;
BEGIN
  BEGIN
    SELECT ID_ROL INTO v_rol FROM ROL WHERE UPPER(NOMBRE)='PILOTO' AND ROWNUM=1;
    UPDATE ROL SET ESTADO_REGISTRO='A' WHERE ID_ROL=v_rol;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    SELECT SEQ_ROL.NEXTVAL INTO v_rol FROM DUAL;
    INSERT INTO ROL(ID_ROL,NOMBRE,DESCRIPCION,FECHA_CREACION,USUARIO_CREACION,ESTADO_REGISTRO)
    VALUES(v_rol,'Piloto','Acceso solamente a entregas asignadas',SYSTIMESTAMP,'INSTALACION','A');
  END;
  BEGIN
    SELECT ID_OPCION INTO v_opcion FROM OPCION WHERE RUTA='/envios/mis-entregas' AND ROWNUM=1;
    UPDATE OPCION SET ESTADO_REGISTRO='A' WHERE ID_OPCION=v_opcion;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    SELECT ID_MENU INTO v_menu FROM OPCION WHERE RUTA='/envios/gestion' AND ROWNUM=1;
    SELECT SEQ_OPCION.NEXTVAL INTO v_opcion FROM DUAL;
    INSERT INTO OPCION(ID_OPCION,ID_MENU,NOMBRE,RUTA,ORDEN,FECHA_CREACION,USUARIO_CREACION,ESTADO_REGISTRO)
    VALUES(v_opcion,v_menu,'Mis entregas','/envios/mis-entregas',2,SYSTIMESTAMP,'INSTALACION','A');
  END;
  SELECT COUNT(*) INTO v_num FROM ROL_OPCION WHERE ID_ROL=v_rol AND ID_OPCION=v_opcion;
  IF v_num=0 THEN
    INSERT INTO ROL_OPCION(ID_ROL_OPCION,ID_ROL,ID_OPCION,PUEDE_CONSULTAR,PUEDE_INSERTAR,PUEDE_ACTUALIZAR,PUEDE_ELIMINAR,FECHA_CREACION,USUARIO_CREACION,ESTADO_REGISTRO)
    VALUES(SEQ_ROL_OPCION.NEXTVAL,v_rol,v_opcion,'S','N','S','N',SYSTIMESTAMP,'INSTALACION','A');
  ELSE
    UPDATE ROL_OPCION SET PUEDE_CONSULTAR='S',PUEDE_INSERTAR='N',PUEDE_ACTUALIZAR='S',PUEDE_ELIMINAR='N',ESTADO_REGISTRO='A'
    WHERE ID_ROL=v_rol AND ID_OPCION=v_opcion;
  END IF;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('ROL PILOTO Y PERMISO MIS ENTREGAS LISTOS. ID_ROL='||v_rol);
EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/
